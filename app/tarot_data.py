def standard_tarot_cards() -> list[dict[str, str | int]]:
    cards: list[dict[str, str | int]] = []
    for number, (name, upright, reversed_value) in enumerate(MAJOR_ARCANA):
        cards.append({
            "name": name,
            "suit": "Старшие Арканы",
            "number": number,
            "description": f"Старший Аркан «{name}».",
            "upright": upright,
            "reversed": reversed_value,
        })

    index = 22
    for suit, data in SUITS.items():
        for rank_index, (rank, rank_theme) in enumerate(RANKS, start=1):
            cards.append({
                "name": f"{rank} {suit}",
                "suit": suit,
                "number": rank_index,
                "description": f"{rank_theme.capitalize()} в сфере: {data['theme']}.",
                "upright": f"{rank_theme.capitalize()}. {data['upright']}",
                "reversed": f"{rank_theme.capitalize()}, но в затруднённой форме. {data['reversed']}",
            })
            index += 1
    return cards
